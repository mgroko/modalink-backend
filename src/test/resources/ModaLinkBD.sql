    SELECT tipo_dato INTO v_tipo_dato
    FROM caracteristica_tecnica
    WHERE id_caracteristica = NEW.id_caracteristica;

    IF v_tipo_dato = 'NUMERICO' THEN
        IF NEW.valor IS NULL THEN
            RAISE EXCEPTION 'Para caracteristicas tecnicas de tipo NUMERICO debe proveerse un valor numerico.';
        END IF;
        BEGIN
            v_numero := NEW.valor::double precision;
        EXCEPTION WHEN invalid_text_representation THEN
            RAISE EXCEPTION 'El valor "%" no es un numero valido para la caracteristica tecnica.', NEW.valor;
        END;

        IF v_numero < 0 THEN
            RAISE EXCEPTION 'La caracteristica tecnica numerica no admite valores negativos.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


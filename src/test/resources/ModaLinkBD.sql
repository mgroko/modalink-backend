-- Creacion automatica de agenda y jornadas laborales al registrar un usuario
-- Adaptado a columnas: margen_actividad_min, hora_inicio_manana, hora_fin_tarde

CREATE OR REPLACE FUNCTION fn_crear_agenda() RETURNS trigger AS $$
DECLARE
    v_id_agenda BIGINT;
BEGIN
    INSERT INTO agenda (margen_actividad_min, id_usuario)
    VALUES (30, NEW.id_usuario)
    RETURNING id_agenda INTO v_id_agenda;

    -- Lunes (1) a Viernes (5), jornada corrida estandar 09:00 a 18:00
    INSERT INTO jornada_agenda (id_agenda, dia_semana, hora_inicio_manana, hora_fin_tarde)
    SELECT v_id_agenda, d, '09:00'::TIME, '18:00'::TIME
    FROM (VALUES (1), (2), (3), (4), (5)) AS v(d);

    RETURN NEW;
END $$ LANGUAGE plpgsql;


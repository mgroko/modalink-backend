-- Trigger para evitar ciclos en la dependencia de actividades
CREATE OR REPLACE FUNCTION fn_dependencia_sin_ciclos()
RETURNS trigger AS $$
BEGIN
    -- Serializa inserciones concurrentes para evitar que dos transacciones
    -- creen A->B y B->A a la vez sin verse entre sí.
    PERFORM pg_advisory_xact_lock(hashtext('dependencia_actividades'));

    -- Arista nueva: predecesora -> sucesora.
    -- Se crea un ciclo si desde la sucesora ya se puede llegar a la predecesora.
    IF EXISTS (
        WITH RECURSIVE descendientes AS (
            SELECT d.id_actividad_sucesora AS id
            FROM dependencia_actividades d
            WHERE d.id_actividad_predecesora = NEW.id_actividad_sucesora
              AND NOT (TG_OP = 'UPDATE'
                       AND d.id_actividad_sucesora    = OLD.id_actividad_sucesora
                       AND d.id_actividad_predecesora = OLD.id_actividad_predecesora)
            UNION
            SELECT d.id_actividad_sucesora
            FROM dependencia_actividades d
            JOIN descendientes x ON d.id_actividad_predecesora = x.id
            WHERE NOT (TG_OP = 'UPDATE'
                       AND d.id_actividad_sucesora    = OLD.id_actividad_sucesora
                       AND d.id_actividad_predecesora = OLD.id_actividad_predecesora)
        )
        SELECT 1 FROM descendientes
        WHERE id = NEW.id_actividad_predecesora
    ) THEN
        RAISE EXCEPTION
            'Dependencia inválida: la actividad % como predecesora de % genera un ciclo',
            NEW.id_actividad_predecesora, NEW.id_actividad_sucesora
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_dependencia_sin_ciclos
BEFORE INSERT OR UPDATE ON dependencia_actividades
FOR EACH ROW
EXECUTE FUNCTION fn_dependencia_sin_ciclos();



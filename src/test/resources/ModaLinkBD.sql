-- Auditoria sobre tabla usuario (Cambios de estado, baja y datos sensibles)
CREATE OR REPLACE FUNCTION fn_auditar_cambio_usuario() RETURNS trigger AS $$
DECLARE
    v_id_tipo_auditoria BIGINT;
    v_id_auditoria BIGINT;
BEGIN
    -- Obtener id_tipo_auditoria según la acción (TG_OP en PostgreSQL es siempre 'INSERT', 'UPDATE' o 'DELETE' en mayúsculas)
    SELECT id_tipo_auditoria INTO v_id_tipo_auditoria
    FROM tipo_accion_auditoria 
    WHERE nombre = TG_OP;

    IF v_id_tipo_auditoria IS NULL THEN
        RAISE EXCEPTION 'No se encontró el tipo de acción de auditoría para la operación %', TG_OP;
    END IF;

    -- Si cambió el estado o se está eliminando el usuario
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND (OLD.estado <> NEW.estado OR OLD.id_rol_global <> NEW.id_rol_global)) THEN
        
        INSERT INTO auditoria (
            usuario_bd,
            entidad_afectada,
            id_afectado,
            fecha_hora,
            ip_usuario,
            id_tipo_auditoria,
            id_usuario
        ) VALUES (
            CURRENT_USER,
            'usuario',
            COALESCE(NEW.id_usuario, OLD.id_usuario),
            clock_timestamp(),
            inet_client_addr()::varchar,
            v_id_tipo_auditoria,
            COALESCE(NEW.id_usuario, OLD.id_usuario)
        ) RETURNING id_auditoria INTO v_id_auditoria;

        -- Registrar detalle del cambio de estado si varió
        IF TG_OP = 'UPDATE' AND OLD.estado <> NEW.estado THEN
            INSERT INTO detalle_auditoria (campo, valor_anterior, valor_nuevo, id_auditoria)
            VALUES ('estado', OLD.estado, NEW.estado, v_id_auditoria);
        END IF;

        -- Registrar detalle del cambio de rol si varió
        IF TG_OP = 'UPDATE' AND OLD.id_rol_global <> NEW.id_rol_global THEN
            INSERT INTO detalle_auditoria (campo, valor_anterior, valor_nuevo, id_auditoria)
            VALUES ('id_rol_global', OLD.id_rol_global::varchar, NEW.id_rol_global::varchar, v_id_auditoria);
        END IF;

        -- Registrar detalle si fue borrado
        IF TG_OP = 'DELETE' THEN
            INSERT INTO detalle_auditoria (campo, valor_anterior, valor_nuevo, id_auditoria)
            VALUES ('registro', OLD.correo, 'ELIMINADO', v_id_auditoria);
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_auditar_cambio_usuario ON usuario;
CREATE TRIGGER trg_auditar_cambio_usuario
    AFTER UPDATE OF estado, id_rol_global OR DELETE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_auditar_cambio_usuario();









BEGIN
    IF EXISTS (
        SELECT 1 FROM perfil
        WHERE id_usuario = NEW.id_usuario
          AND id_profesion = NEW.id_profesion
          AND estado IN ('ACTIVO', 'PENDIENTE_BAJA')
          AND id_perfil IS DISTINCT FROM NEW.id_perfil
    ) THEN
        RAISE EXCEPTION 'El usuario ya posee un perfil activo o en trámite de baja para la profesión indicada.';
    END IF;

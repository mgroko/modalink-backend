-- Consistencia: valor XOR id_valor segun el tipo_dato de la caracteristica tecnica
CREATE OR REPLACE FUNCTION chk_caracteristica_perfil_valor() RETURNS trigger AS $$
DECLARE
    v_tipo_dato VARCHAR(50);
BEGIN
    SELECT tipo_dato INTO v_tipo_dato
    FROM caracteristica_tecnica
    WHERE id_caracteristica = NEW.id_caracteristica;

    IF v_tipo_dato = 'ENUMERADO' THEN
        IF NEW.id_valor IS NULL OR NEW.valor IS NOT NULL THEN
            RAISE EXCEPTION 'Para caracteristicas de tipo ENUMERADO debe especificarse id_valor y el campo valor debe ser nulo.';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM valor_caracteristica vc
            WHERE vc.id_valor = NEW.id_valor
              AND vc.id_caracteristica = NEW.id_caracteristica
        ) THEN
            RAISE EXCEPTION 'El id_valor no pertenece a la caracteristica tecnica indicada.';
        END IF;
    ELSE -- 'TEXTO' o 'NUMERICO'
        IF NEW.valor IS NULL OR NEW.id_valor IS NOT NULL THEN
            RAISE EXCEPTION 'Para caracteristicas de tipo TEXTO o NUMERICO debe especificarse valor y id_valor debe ser nulo.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ============================================================
-- UC-09: Autenticación con Google OAuth
-- ============================================================
-- 1. Crea la tabla usuario_identidad.
-- 2. Hace backfill de las identidades de los usuarios existentes.
-- 3. Elimina las columnas viejas usuario.proveedor_auth e usuario.id_externo.
--
-- IMPORTANTE: ejecutar con la aplicación detenida. El backfill preserva a
-- todos los usuarios locales actuales; no se modifica su correo ni su
-- password_hash.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS usuario_identidad(
    id_identidad                   int8             GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario                     int8             NOT NULL,
    proveedor                      varchar(20)      NOT NULL,
    id_externo                     varchar(255),
    correo                         varchar(255)     NOT NULL,
    correo_verificado              boolean          NOT NULL DEFAULT false,
    fecha_vinculacion              timestamp        NOT NULL DEFAULT now(),
    CONSTRAINT "PK_usuario_identidad" PRIMARY KEY (id_identidad),
    CONSTRAINT fk_usuario_identidad_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT chk_usuario_identidad_proveedor CHECK (proveedor IN ('LOCAL', 'GOOGLE')),
    CONSTRAINT chk_usuario_identidad_google_sub CHECK (proveedor <> 'GOOGLE' OR id_externo IS NOT NULL),
    CONSTRAINT uq_usuario_identidad_proveedor_externo UNIQUE (proveedor, id_externo),
    CONSTRAINT uq_usuario_identidad_usuario_proveedor UNIQUE (id_usuario, proveedor)
);

-- Todos los usuarios existentes tienen credenciales locales.
INSERT INTO usuario_identidad (id_usuario, proveedor, id_externo, correo, correo_verificado)
SELECT u.id_usuario, 'LOCAL', NULL, lower(trim(u.correo)), false
FROM usuario u
WHERE NOT EXISTS (
    SELECT 1
    FROM usuario_identidad ui
    WHERE ui.id_usuario = u.id_usuario
      AND ui.proveedor = 'LOCAL'
);

-- Si la base ya tenía usuarios GOOGLE (columnas viejas), se migran también.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'usuario'
          AND column_name = 'proveedor_auth'
    ) THEN
        INSERT INTO usuario_identidad (id_usuario, proveedor, id_externo, correo, correo_verificado)
        SELECT u.id_usuario, 'GOOGLE', u.id_externo, lower(trim(u.correo)), true
        FROM usuario u
        WHERE u.proveedor_auth = 'GOOGLE'
          AND u.id_externo IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM usuario_identidad ui
              WHERE ui.proveedor = 'GOOGLE'
                AND ui.id_externo = u.id_externo
          );
    END IF;
END $$;

ALTER TABLE usuario DROP CONSTRAINT IF EXISTS chk_usuario_proveedor;
ALTER TABLE usuario DROP COLUMN IF EXISTS proveedor_auth;
ALTER TABLE usuario DROP COLUMN IF EXISTS id_externo;

COMMIT;

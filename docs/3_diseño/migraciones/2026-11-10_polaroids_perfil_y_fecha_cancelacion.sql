-- Polaroids de perfiles de modelo + fecha de cancelación de proyecto
-- Migración para bases existentes. Ejecutar con la aplicación detenida.
--
-- Es idempotente: usa IF NOT EXISTS, bloques DO y ON CONFLICT.

BEGIN;

-- 1. Fecha de cancelación para el historial de proyectos del perfil.
ALTER TABLE proyecto
    ADD COLUMN IF NOT EXISTS fecha_cancelacion timestamp;

CREATE INDEX IF NOT EXISTS "IDX_proyecto_historial_perfil"
    ON proyecto (estado, fecha_finalizacion DESC, fecha_cancelacion DESC);

-- 2. Catálogo fijo de grupos y tipos de polaroid.
CREATE TABLE IF NOT EXISTS grupo_polaroid(
    id_grupo_polaroid int8         GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo            varchar(50)  NOT NULL,
    nombre            varchar(100) NOT NULL,
    CONSTRAINT "PK_grupo_polaroid" PRIMARY KEY (id_grupo_polaroid)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UQ_grupo_polaroid_codigo"
    ON grupo_polaroid(codigo);
CREATE UNIQUE INDEX IF NOT EXISTS "UQ_grupo_polaroid_nombre"
    ON grupo_polaroid(nombre);

CREATE TABLE IF NOT EXISTS tipo_polaroid(
    id_tipo_polaroid  int8         GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_grupo_polaroid int8         NOT NULL,
    codigo            varchar(50)  NOT NULL,
    nombre            varchar(100) NOT NULL,
    CONSTRAINT "PK_tipo_polaroid" PRIMARY KEY (id_tipo_polaroid)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UQ_tipo_polaroid_codigo"
    ON tipo_polaroid(codigo);
CREATE UNIQUE INDEX IF NOT EXISTS "UQ_tipo_polaroid_grupo_nombre"
    ON tipo_polaroid(id_grupo_polaroid, nombre);

-- 3. Tipo de cada polaroid.
ALTER TABLE polaroid_perfil
    ADD COLUMN IF NOT EXISTS id_tipo_polaroid int8;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'Reftipo_polaroid'
    ) THEN
        ALTER TABLE polaroid_perfil
            ADD CONSTRAINT "Reftipo_polaroid"
            FOREIGN KEY (id_tipo_polaroid)
            REFERENCES tipo_polaroid(id_tipo_polaroid);
    END IF;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'Refgrupo_polaroid'
    ) THEN
        ALTER TABLE tipo_polaroid
            ADD CONSTRAINT "Refgrupo_polaroid"
            FOREIGN KEY (id_grupo_polaroid)
            REFERENCES grupo_polaroid(id_grupo_polaroid);
    END IF;
END
$$;

-- Si no hay polaroids históricas sin tipo, se puede reforzar NOT NULL.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM polaroid_perfil WHERE id_tipo_polaroid IS NULL) THEN
        ALTER TABLE polaroid_perfil ALTER COLUMN id_tipo_polaroid SET NOT NULL;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS "IDX_miembros_proyecto_historial"
    ON miembros_proyecto (id_perfil, estado_participacion, id_proyecto);

CREATE INDEX IF NOT EXISTS "IDX_polaroid_perfil_perfil_orden"
    ON polaroid_perfil (id_perfil, orden);

-- 4. Semilla: 3 planos x 3 ángulos.
INSERT INTO grupo_polaroid (id_grupo_polaroid, codigo, nombre) VALUES
    (1, 'PRIMER_PLANO',     'Primer plano'),
    (2, 'PLANO_AMERICANO',  'Plano americano'),
    (3, 'CUERPO_COMPLETO',  'Cuerpo completo')
ON CONFLICT (id_grupo_polaroid) DO UPDATE
    SET codigo = EXCLUDED.codigo,
        nombre = EXCLUDED.nombre;

INSERT INTO tipo_polaroid (id_tipo_polaroid, id_grupo_polaroid, codigo, nombre) VALUES
    (1, 1, 'PRIMER_PLANO_FRENTE',      'De frente'),
    (2, 1, 'PRIMER_PLANO_PERFIL',      'De perfil'),
    (3, 1, 'PRIMER_PLANO_ESPALDAS',    'De espaldas'),
    (4, 2, 'PLANO_AMERICANO_FRENTE',   'De frente'),
    (5, 2, 'PLANO_AMERICANO_PERFIL',   'De perfil'),
    (6, 2, 'PLANO_AMERICANO_ESPALDAS', 'De espaldas'),
    (7, 3, 'CUERPO_COMPLETO_FRENTE',   'De frente'),
    (8, 3, 'CUERPO_COMPLETO_PERFIL',   'De perfil'),
    (9, 3, 'CUERPO_COMPLETO_ESPALDAS', 'De espaldas')
ON CONFLICT (id_tipo_polaroid) DO UPDATE
    SET id_grupo_polaroid = EXCLUDED.id_grupo_polaroid,
        codigo = EXCLUDED.codigo,
        nombre = EXCLUDED.nombre;

SELECT setval(pg_get_serial_sequence('grupo_polaroid', 'id_grupo_polaroid'),
              COALESCE(MAX(id_grupo_polaroid), 1)) FROM grupo_polaroid;
SELECT setval(pg_get_serial_sequence('tipo_polaroid', 'id_tipo_polaroid'),
              COALESCE(MAX(id_tipo_polaroid), 1)) FROM tipo_polaroid;

COMMIT;
